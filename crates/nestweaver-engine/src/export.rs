//! Graph export to Cypher (Neo4j), GraphML, and Mermaid formats.

use std::collections::HashMap;
use std::io::Write;

use nestweaver_store::GraphStore;

// ── Cypher export ────────────────────────────────────────────────────────────

/// Escape a string value for Cypher string literals.
/// Wraps in single quotes, escaping internal single quotes and backslashes.
fn cypher_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('\'');
    for ch in s.chars() {
        match ch {
            '\'' => out.push_str("\\'"),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(ch),
        }
    }
    out.push('\'');
    out
}

/// Map database edge type labels to cleaner Cypher relationship names.
fn cypher_edge_label(db_label: &str) -> &str {
    match db_label {
        "EXTENDS_SYM" => "EXTENDS",
        "IMPLEMENTS_SYM" => "IMPLEMENTS",
        "INCLUDES_SYM" => "INCLUDES",
        other => other,
    }
}

/// Export the graph as Neo4j Cypher CREATE statements.
///
/// Generates CREATE statements for Repo, File, and Symbol nodes, followed
/// by MATCH/CREATE statements for edges. All values are properly escaped
/// (no string interpolation of raw user data into Cypher structure).
pub fn export_cypher(store: &GraphStore, writer: &mut dyn Write) -> anyhow::Result<()> {
    writeln!(writer, "// NestWeaver graph export — Neo4j Cypher")?;
    writeln!(
        writer,
        "// Generated by `nestweaver export --format cypher`"
    )?;
    writeln!(writer)?;

    // ── Repo nodes ───────────────────────────────────────────────────────
    let repos = store.list_repos(None).map_err(|e| anyhow::anyhow!("{e}"))?;
    for repo in &repos {
        writeln!(
            writer,
            "CREATE (:Repo {{uid: {}, url: {}, indexed_sha: {}, instance_id: {}}});",
            cypher_escape(&repo.uid),
            cypher_escape(&repo.url),
            cypher_escape(&repo.indexed_sha),
            cypher_escape(&repo.instance_id),
        )?;
    }
    if !repos.is_empty() {
        writeln!(writer)?;
    }

    // ── File nodes ───────────────────────────────────────────────────────
    for repo in &repos {
        let files = store
            .list_files_by_repo(&repo.uid)
            .map_err(|e| anyhow::anyhow!("{e}"))?;
        for (file_uid, file_path) in &files {
            writeln!(
                writer,
                "CREATE (:File {{uid: {}, path: {}, repo_uid: {}}});",
                cypher_escape(file_uid),
                cypher_escape(file_path),
                cypher_escape(&repo.uid),
            )?;
        }
    }
    writeln!(writer)?;

    // ── Symbol nodes ─────────────────────────────────────────────────────
    let symbols = store
        .list_all_symbols()
        .map_err(|e| anyhow::anyhow!("{e}"))?;
    // F-13: the `pagerank_score` column is never populated; the real scores
    // live in the store's PageRank cache (same source `hubs` reads).
    let pagerank = store.pagerank_scores();
    for sym in &symbols {
        let pr = pagerank
            .get(&sym.uid)
            .copied()
            .or(sym.pagerank_score)
            .unwrap_or(0.0);
        writeln!(
            writer,
            "CREATE (:Symbol {{uid: {}, name: {}, kind: {}, file: {}, line: {}, pagerank: {:.6}}});",
            cypher_escape(&sym.uid),
            cypher_escape(&sym.name),
            cypher_escape(&sym.kind.to_string()),
            cypher_escape(&sym.file_path),
            sym.start_line,
            pr,
        )?;
    }
    if !symbols.is_empty() {
        writeln!(writer)?;
    }

    // ── Edges ────────────────────────────────────────────────────────────
    let typed_edges = store
        .load_typed_edges()
        .map_err(|e| anyhow::anyhow!("{e}"))?;
    for (src, dst, edge_type, confidence, evidence) in &typed_edges {
        if evidence.is_empty() {
            writeln!(
                writer,
                "MATCH (a {{uid: {}}}), (b {{uid: {}}}) CREATE (a)-[:{} {{confidence: {:.4}}}]->(b);",
                cypher_escape(src),
                cypher_escape(dst),
                cypher_edge_label(edge_type),
                confidence,
            )?;
        } else {
            writeln!(
                writer,
                "MATCH (a {{uid: {}}}), (b {{uid: {}}}) CREATE (a)-[:{} {{confidence: {:.4}, evidence: {}}}]->(b);",
                cypher_escape(src),
                cypher_escape(dst),
                cypher_edge_label(edge_type),
                confidence,
                cypher_escape(evidence),
            )?;
        }
    }

    Ok(())
}

// ── GraphML export ───────────────────────────────────────────────────────────

/// Escape a string for safe inclusion in XML attribute values or text content.
fn xml_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&apos;"),
            _ => out.push(ch),
        }
    }
    out
}

/// Export the graph as GraphML XML, compatible with Gephi and yEd.
///
/// Emits Repo, File, and Symbol nodes with their properties, and all
/// code-level edges (CALLS, IMPORTS, EXTENDS, IMPLEMENTS, MEMBER_OF, INCLUDES).
pub fn export_graphml(store: &GraphStore, writer: &mut dyn Write) -> anyhow::Result<()> {
    // XML header
    writeln!(writer, r#"<?xml version="1.0" encoding="UTF-8"?>"#)?;
    writeln!(
        writer,
        r#"<graphml xmlns="http://graphml.graphdrawing.org/graphml"
         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://graphml.graphdrawing.org/graphml http://graphml.graphdrawing.org/xmlns/1.0/graphml.xsd">"#
    )?;

    // Key definitions for node attributes
    writeln!(
        writer,
        r#"  <key id="label" for="node" attr.name="label" attr.type="string"/>"#
    )?;
    writeln!(
        writer,
        r#"  <key id="kind" for="node" attr.name="kind" attr.type="string"/>"#
    )?;
    writeln!(
        writer,
        r#"  <key id="file_path" for="node" attr.name="file_path" attr.type="string"/>"#
    )?;
    writeln!(
        writer,
        r#"  <key id="pagerank" for="node" attr.name="pagerank" attr.type="double"/>"#
    )?;

    // Key definitions for edge attributes
    writeln!(
        writer,
        r#"  <key id="edge_type" for="edge" attr.name="type" attr.type="string"/>"#
    )?;
    writeln!(
        writer,
        r#"  <key id="confidence" for="edge" attr.name="confidence" attr.type="double"/>"#
    )?;

    writeln!(writer, r#"  <graph id="G" edgedefault="directed">"#)?;

    // ── Repo nodes ───────────────────────────────────────────────────────
    let repos = store.list_repos(None).map_err(|e| anyhow::anyhow!("{e}"))?;
    for repo in &repos {
        writeln!(
            writer,
            r#"    <node id="{}">
      <data key="label">{}</data>
      <data key="kind">Repo</data>
    </node>"#,
            xml_escape(&repo.uid),
            xml_escape(&repo.url),
        )?;
    }

    // ── File nodes ───────────────────────────────────────────────────────
    for repo in &repos {
        let files = store
            .list_files_by_repo(&repo.uid)
            .map_err(|e| anyhow::anyhow!("{e}"))?;
        for (file_uid, file_path) in &files {
            writeln!(
                writer,
                r#"    <node id="{}">
      <data key="label">{}</data>
      <data key="kind">File</data>
      <data key="file_path">{}</data>
    </node>"#,
                xml_escape(file_uid),
                xml_escape(file_path),
                xml_escape(file_path),
            )?;
        }
    }

    // ── Symbol nodes ─────────────────────────────────────────────────────
    let symbols = store
        .list_all_symbols()
        .map_err(|e| anyhow::anyhow!("{e}"))?;
    // F-13: the `pagerank_score` column is never populated; the real scores
    // live in the store's PageRank cache (same source `hubs` reads).
    let pagerank = store.pagerank_scores();
    for sym in &symbols {
        let pr = pagerank
            .get(&sym.uid)
            .copied()
            .or(sym.pagerank_score)
            .unwrap_or(0.0);
        writeln!(
            writer,
            r#"    <node id="{}">
      <data key="label">{}</data>
      <data key="kind">{}</data>
      <data key="file_path">{}</data>
      <data key="pagerank">{:.6}</data>
    </node>"#,
            xml_escape(&sym.uid),
            xml_escape(&sym.name),
            xml_escape(&sym.kind.to_string()),
            xml_escape(&sym.file_path),
            pr,
        )?;
    }

    // ── Edges ────────────────────────────────────────────────────────────
    let typed_edges = store
        .load_typed_edges()
        .map_err(|e| anyhow::anyhow!("{e}"))?;
    for (idx, (src, dst, edge_type, confidence, _evidence)) in typed_edges.iter().enumerate() {
        writeln!(
            writer,
            r#"    <edge id="e{}" source="{}" target="{}">
      <data key="edge_type">{}</data>
      <data key="confidence">{:.4}</data>
    </edge>"#,
            idx,
            xml_escape(src),
            xml_escape(dst),
            xml_escape(cypher_edge_label(edge_type)),
            confidence,
        )?;
    }

    writeln!(writer, "  </graph>")?;
    writeln!(writer, "</graphml>")?;

    Ok(())
}

// ── Mermaid export ───────────────────────────────────────────────────────────

/// Sanitize a string for use as a Mermaid node ID.
/// Removes special characters that break Mermaid syntax.
fn mermaid_id(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect()
}

/// Sanitize a string for use as a Mermaid node label.
/// Wraps in quotes and escapes breaking characters.
fn mermaid_label(s: &str) -> String {
    let escaped: String = s
        .chars()
        .map(|c| match c {
            '"' => '\'',
            '|' | '[' | ']' | '{' | '}' | '(' | ')' | '<' | '>' => '_',
            _ => c,
        })
        .collect();
    format!("\"{escaped}\"")
}

/// Export the top-N symbols (by PageRank) as a Mermaid flowchart, grouped by file.
///
/// Only symbols that appear in the top-N set and edges between them are included.
pub fn export_mermaid(
    store: &GraphStore,
    top_n: usize,
    writer: &mut dyn Write,
) -> anyhow::Result<()> {
    let symbols = store
        .list_all_symbols()
        .map_err(|e| anyhow::anyhow!("{e}"))?;

    // Sort by PageRank descending, take top N. F-13: the `pagerank_score`
    // column is never populated; rank by the store's PageRank cache (the same
    // source `hubs` reads), falling back to the column for stores without a
    // computed cache.
    let pagerank = store.pagerank_scores();
    let mut ranked = symbols;
    ranked.sort_by(|a, b| {
        let pa = pagerank
            .get(&a.uid)
            .copied()
            .or(a.pagerank_score)
            .unwrap_or(0.0);
        let pb = pagerank
            .get(&b.uid)
            .copied()
            .or(b.pagerank_score)
            .unwrap_or(0.0);
        pb.partial_cmp(&pa).unwrap_or(std::cmp::Ordering::Equal)
    });
    ranked.truncate(top_n);

    // Build a set of included UIDs for edge filtering.
    let included: std::collections::HashSet<&str> = ranked.iter().map(|s| s.uid.as_str()).collect();

    // Group symbols by file_path for subgraph rendering.
    let mut by_file: HashMap<&str, Vec<&nestweaver_schema::Symbol>> = HashMap::new();
    for sym in &ranked {
        by_file.entry(sym.file_path.as_str()).or_default().push(sym);
    }
    // Sort file groups for deterministic output.
    let mut file_keys: Vec<&str> = by_file.keys().copied().collect();
    file_keys.sort();

    writeln!(writer, "flowchart LR")?;

    // Emit subgraphs grouped by file.
    for file_path in &file_keys {
        let syms = &by_file[file_path];
        let subgraph_id = mermaid_id(file_path);
        writeln!(
            writer,
            "  subgraph {} [{}]",
            subgraph_id,
            mermaid_label(file_path)
        )?;
        for sym in syms {
            let node_id = mermaid_id(&sym.uid);
            let label = format!("{} ({})", sym.name, sym.kind);
            writeln!(writer, "    {}[{}]", node_id, mermaid_label(&label))?;
        }
        writeln!(writer, "  end")?;
    }

    // Emit edges between included symbols.
    let typed_edges = store
        .load_typed_edges()
        .map_err(|e| anyhow::anyhow!("{e}"))?;
    for (src, dst, _edge_type, _confidence, _evidence) in &typed_edges {
        if included.contains(src.as_str()) && included.contains(dst.as_str()) {
            writeln!(writer, "  {} --> {}", mermaid_id(src), mermaid_id(dst))?;
        }
    }

    Ok(())
}

