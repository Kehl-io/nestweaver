#[cfg(test)]
mod tests {
    use super::*;
    use nestweaver_schema::{EdgeType, ResolvedEdge, SymbolKind, Visibility};

    fn test_store() -> GraphStore {
        GraphStore::in_memory().unwrap()
    }

    fn make_symbol(uid: &str, name: &str, file_path: &str) -> nestweaver_schema::Symbol {
        nestweaver_schema::Symbol {
            uid: uid.to_string(),
            name: name.to_string(),
            kind: SymbolKind::Function,
            repo_uid: "repo-1".to_string(),
            file_path: file_path.to_string(),
            start_line: 10,
            end_line: 10,
            signature: format!("fn {name}()"),
            summary: None,
            content_hash: "hash".to_string(),
            embedding: None,
            pagerank_score: Some(0.5),
            is_entry_point: false,
            entry_point_kind: None,
            visibility: Visibility::Inferred,
            type_info: None,
            framework_hint: None,
            canonical_id: None,
        }
    }

    fn populated_store() -> GraphStore {
        let store = test_store();
        store
            .insert_repo(&nestweaver_schema::Repo {
                uid: "repo-1".to_string(),
                url: "https://github.com/example/repo".to_string(),
                indexed_sha: "abc123".to_string(),
                staleness_commits_behind: 0,
                instance_id: "default".to_string(),
                name: None,
                root_path: None,
            })
            .unwrap();

        let sym_a = make_symbol("sym-a", "fn_alpha", "src/alpha.rs");
        let sym_b = make_symbol("sym-b", "fn_beta", "src/beta.rs");
        store.insert_symbol(&sym_a).unwrap();
        store.insert_symbol(&sym_b).unwrap();

        store
            .insert_edge(&ResolvedEdge {
                source_uid: "sym-a".to_string(),
                target_uid: "sym-b".to_string(),
                edge_type: EdgeType::Calls,
                confidence: 0.9,
                link_type: None,
                evidence: vec![],
            })
            .unwrap();

        store
    }

    #[test]
    fn cypher_export_contains_create_statements() {
        let store = populated_store();
        let mut buf = Vec::new();
        export_cypher(&store, &mut buf).unwrap();
        let output = String::from_utf8(buf).unwrap();

        assert!(output.contains("CREATE (:Repo"));
        assert!(output.contains("CREATE (:Symbol"));
        assert!(output.contains("fn_alpha"));
        assert!(output.contains("fn_beta"));
    }

    #[test]
    fn cypher_export_includes_edges() {
        let store = populated_store();
        let mut buf = Vec::new();
        export_cypher(&store, &mut buf).unwrap();
        let output = String::from_utf8(buf).unwrap();

        assert!(output.contains("MATCH"));
        assert!(output.contains(":CALLS"));
        assert!(output.contains("confidence"));
    }

    #[test]
    fn cypher_escape_handles_special_chars() {
        assert_eq!(cypher_escape("it's"), "'it\\'s'");
        assert_eq!(cypher_escape("a\\b"), "'a\\\\b'");
        assert_eq!(cypher_escape("line\nnew"), "'line\\nnew'");
    }

    #[test]
    fn graphml_export_produces_valid_xml_structure() {
        let store = populated_store();
        let mut buf = Vec::new();
        export_graphml(&store, &mut buf).unwrap();
        let output = String::from_utf8(buf).unwrap();

        assert!(output.contains("<?xml version="));
        assert!(output.contains("<graphml"));
        assert!(output.contains("<graph id="));
        assert!(output.contains("<node id="));
        assert!(output.contains("fn_alpha"));
        assert!(output.contains("fn_beta"));
        assert!(output.contains("</graphml>"));
    }

    #[test]
    fn graphml_export_includes_edges() {
        let store = populated_store();
        let mut buf = Vec::new();
        export_graphml(&store, &mut buf).unwrap();
        let output = String::from_utf8(buf).unwrap();

        assert!(output.contains("<edge id="));
        assert!(output.contains("CALLS"));
        assert!(output.contains("confidence"));
    }

    #[test]
    fn xml_escape_handles_special_chars() {
        assert_eq!(xml_escape("a&b"), "a&amp;b");
        assert_eq!(xml_escape("a<b>c"), "a&lt;b&gt;c");
        assert_eq!(xml_escape(r#"a"b"#), "a&quot;b");
    }

    #[test]
    fn mermaid_export_produces_flowchart() {
        let store = populated_store();
        let mut buf = Vec::new();
        export_mermaid(&store, 50, &mut buf).unwrap();
        let output = String::from_utf8(buf).unwrap();

        assert!(output.starts_with("flowchart LR"));
        assert!(output.contains("subgraph"));
        assert!(output.contains("fn_alpha"));
        assert!(output.contains("fn_beta"));
        // Edge from sym-a to sym-b should be present
        assert!(output.contains("-->"));
    }

    #[test]
    fn mermaid_id_sanitizes_special_chars() {
        assert_eq!(mermaid_id("src/main.rs"), "src_main_rs");
        assert_eq!(mermaid_id("a:b:c"), "a_b_c");
    }

    #[test]
    fn mermaid_top_n_limits_output() {
        let store = test_store();
        // Insert 5 symbols with decreasing PageRank
        for i in 0..5u32 {
            let mut sym = make_symbol(&format!("sym-{i}"), &format!("fn_{i}"), "src/lib.rs");
            sym.pagerank_score = Some(1.0 - (i as f64 * 0.1));
            store.insert_symbol(&sym).unwrap();
        }

        let mut buf = Vec::new();
        export_mermaid(&store, 2, &mut buf).unwrap();
        let output = String::from_utf8(buf).unwrap();

        // Only top 2 should appear
        assert!(output.contains("fn_0"));
        assert!(output.contains("fn_1"));
        assert!(!output.contains("fn_4"));
    }

    /// populated_store plus a second caller of sym-b: two callers make the
    /// callee's computed PageRank strictly higher than each caller's (with a
    /// single caller the store's reverse-edge weighting ties them at 0.5).
    /// Every symbol carries the same 0.5 column score, so any difference in
    /// the exported values must come from the cache — a real F-13 regression.
    fn ranked_store() -> GraphStore {
        let store = populated_store();
        store
            .insert_symbol(&make_symbol("sym-c", "fn_gamma", "src/gamma.rs"))
            .unwrap();
        store
            .insert_edge(&ResolvedEdge {
                source_uid: "sym-c".to_string(),
                target_uid: "sym-b".to_string(),
                edge_type: EdgeType::Calls,
                confidence: 0.9,
                link_type: None,
                evidence: vec![],
            })
            .unwrap();
        store
    }

    #[test]
    fn export_uses_computed_pagerank_not_zero_column() {
        // F-13: the `pagerank_score` column is never populated in production;
        // export must carry the store's computed PageRank cache values.
        let store = ranked_store();
        let scores = store.pagerank_scores();
        assert!(
            scores.contains_key("sym-b"),
            "cache should compute scores on demand"
        );
        assert!(
            (scores["sym-b"] - 0.5).abs() > 1e-9,
            "cache score must differ from the 0.5 column value to prove the source: {scores:?}"
        );

        let mut buf = Vec::new();
        export_cypher(&store, &mut buf).unwrap();
        let output = String::from_utf8(buf).unwrap();
        let expected = format!("pagerank: {:.6}", scores["sym-b"]);
        assert!(
            output.contains(&expected),
            "cypher export must carry the cache score {expected}"
        );

        let mut buf = Vec::new();
        export_graphml(&store, &mut buf).unwrap();
        let output = String::from_utf8(buf).unwrap();
        let expected = format!("<data key=\"pagerank\">{:.6}</data>", scores["sym-b"]);
        assert!(
            output.contains(&expected),
            "graphml export must carry the cache score {expected}"
        );
    }

    #[test]
    fn mermaid_top_n_ranks_by_computed_pagerank() {
        // F-13: make_symbol gives every symbol the same column score (0.5),
        // but sym-b has two inbound CALLS edges, so the computed PageRank
        // must rank it first.
        let store = ranked_store();
        let scores = store.pagerank_scores();
        assert!(
            scores["sym-b"] > scores["sym-a"],
            "callee must outrank caller: {scores:?}"
        );
        let mut buf = Vec::new();
        export_mermaid(&store, 1, &mut buf).unwrap();
        let output = String::from_utf8(buf).unwrap();
        assert!(output.contains("fn_beta"), "top-1 must be the callee");
        assert!(!output.contains("fn_alpha"), "top-1 must not be the caller");
    }

    #[test]
    fn export_empty_store_produces_valid_output() {
        let store = test_store();

        let mut buf = Vec::new();
        export_cypher(&store, &mut buf).unwrap();
        let cypher = String::from_utf8(buf).unwrap();
        assert!(cypher.contains("NestWeaver graph export"));

        let mut buf = Vec::new();
        export_graphml(&store, &mut buf).unwrap();
        let graphml = String::from_utf8(buf).unwrap();
        assert!(graphml.contains("</graphml>"));

        let mut buf = Vec::new();
        export_mermaid(&store, 50, &mut buf).unwrap();
        let mermaid = String::from_utf8(buf).unwrap();
        assert!(mermaid.starts_with("flowchart LR"));
    }
}
