use nestweaver_store::GraphStore;

use crate::config::InstanceConfig;

/// Generate AGENTS.md content from the indexed graph.
///
/// Returns a markdown string that summarizes the indexed repositories,
/// architectural skeleton, knowledge vaults, and available MCP tools.
/// Intended to be written to `AGENTS.md` at the workspace root so AI
/// agents pick it up automatically at session start.
///
/// Pass an optional `InstanceConfig` to include declared `[[features]]` and
/// `[[links]]` sections in the output. When `None`, those sections are omitted
/// but the cross-repo edges discovered in the graph are still shown.
pub fn generate_guide(
    store: &GraphStore,
    config: Option<&InstanceConfig>,
) -> Result<String, anyhow::Error> {
    let mut out = String::new();

    out.push_str("# Codebase Intelligence Guide\n\n");
    out.push_str("> Auto-generated by NestWeaver. Do not edit manually.\n\n");

    // Section 1: Repositories
    out.push_str("## Repositories\n\n");
    let repos = store.list_repos(None).unwrap_or_default();
    if repos.is_empty() {
        out.push_str("No repositories indexed yet.\n\n");
    } else {
        for repo in &repos {
            let sha_short = if repo.indexed_sha.len() >= 8 {
                &repo.indexed_sha[..8]
            } else {
                &repo.indexed_sha
            };
            out.push_str(&format!("- `{}` (sha: {})\n", repo.url, sha_short));
        }
        out.push('\n');
    }

    // Section 2: Architecture overview (repo map)
    out.push_str("## Architecture\n\n");
    match crate::query::generate_repo_map(store, 2000) {
        Ok(map) => {
            out.push_str("```\n");
            out.push_str(&map);
            out.push_str("\n```\n\n");
        }
        Err(_) => {
            out.push_str("No symbols indexed yet.\n\n");
        }
    }

    // Section 3: Cross-repo links discovered in the graph
    let cross_links = store.list_all_cross_repo_links(50).unwrap_or_default();
    if !cross_links.is_empty() {
        // Build a repo-uid → short name map from indexed repos.
        let repo_name: std::collections::HashMap<String, String> = repos
            .iter()
            .map(|r| {
                // Derive a short name: last path component of the URL.
                let short = r
                    .url
                    .trim_end_matches('/')
                    .rsplit('/')
                    .next()
                    .unwrap_or(&r.url)
                    .trim_end_matches(".git")
                    .to_string();
                (r.uid.clone(), short)
            })
            .collect();

        // Group by (source_repo_uid, target_repo_uid, link_type) to collect shared symbols.
        use std::collections::BTreeMap;
        let mut groups: BTreeMap<(String, String, String), Vec<String>> = BTreeMap::new();
        for link in &cross_links {
            let src_repo = link
                .source_repo_uid
                .as_deref()
                .map(|u| repo_name.get(u).cloned().unwrap_or_else(|| u.to_string()))
                .unwrap_or_else(|| "?".to_string());
            let tgt_repo = link
                .target_repo_uid
                .as_deref()
                .map(|u| repo_name.get(u).cloned().unwrap_or_else(|| u.to_string()))
                .unwrap_or_else(|| "?".to_string());
            groups
                .entry((src_repo, tgt_repo, link.link_type.clone()))
                .or_default()
                .push(link.source_name.clone());
        }

        out.push_str("## Cross-Repository Links\n\n");
        out.push_str("| From | To | Type | Shared Symbols |\n");
        out.push_str("|------|----|------|---------------|\n");
        for ((src, tgt, ltype), mut symbols) in groups {
            symbols.sort();
            symbols.dedup();
            let syms_preview: Vec<&str> = symbols.iter().take(5).map(|s| s.as_str()).collect();
            let syms_str = if symbols.len() > 5 {
                format!("{}, … (+{})", syms_preview.join(", "), symbols.len() - 5)
            } else {
                syms_preview.join(", ")
            };
            out.push_str(&format!("| {src} | {tgt} | {ltype} | {syms_str} |\n"));
        }
        out.push('\n');
    }

    // Section 4: Declared links from instance config
    if let Some(cfg) = config {
        if let Some(links) = &cfg.links
            && !links.is_empty()
        {
            out.push_str("## Declared Links\n\n");
            out.push_str("| From | To | Type | Description |\n");
            out.push_str("|------|----|------|-------------|\n");
            for link in links {
                let desc = link.description.as_deref().unwrap_or("");
                out.push_str(&format!(
                    "| {} | {} | {} | {} |\n",
                    link.from, link.to, link.link_type, desc
                ));
            }
            out.push('\n');
        }

        // Section 5: Feature bundles from instance config
        if let Some(features) = &cfg.features
            && !features.is_empty()
        {
            out.push_str("## Feature Bundles\n\n");
            for feat in features {
                out.push_str(&format!("### {}\n\n", feat.name));
                if let Some(desc) = &feat.description {
                    out.push_str(&format!("> {desc}\n\n"));
                }
                out.push_str(&format!("- **Repos:** {}\n", feat.repos.join(", ")));
                out.push_str(&format!(
                    "- **Entry Points:** {}\n",
                    feat.entry_points.join(", ")
                ));
                out.push('\n');
            }
        }
    }

    // Section 6: Projects
    let projects = store.list_projects().unwrap_or_default();
    let empty_projects: Vec<crate::config::ProjectConfig> = Vec::new();
    let config_projects: &[crate::config::ProjectConfig] = config
        .map(|c| c.projects.as_slice())
        .unwrap_or(&empty_projects);
    // Merge: start from store projects, then add any config entries not already present.
    let mut all_project_names: Vec<String> = projects.iter().map(|p| p.name.clone()).collect();
    for cp in config_projects {
        if !all_project_names
            .iter()
            .any(|n| n.eq_ignore_ascii_case(&cp.name))
        {
            all_project_names.push(cp.name.clone());
        }
    }
    if !all_project_names.is_empty() {
        out.push_str("## Projects\n\n");
        for project_name in &all_project_names {
            // Find the store project (may be None if only in config).
            let store_project = projects
                .iter()
                .find(|p| p.name.eq_ignore_ascii_case(project_name));
            // Find the config project entry (if any).
            let cfg_project = config_projects
                .iter()
                .find(|cp| cp.name.eq_ignore_ascii_case(project_name));

            out.push_str(&format!("### {project_name}\n\n"));

            // Description from config.
            if let Some(desc) = cfg_project.and_then(|cp| cp.description.as_deref()) {
                out.push_str(&format!("- **Description:** {desc}\n"));
            } else if let Some(desc) = store_project.and_then(|p| p.summary.as_deref()) {
                out.push_str(&format!("- **Description:** {desc}\n"));
            }

            // Aliases from config.
            if let Some(cp) = cfg_project
                && !cp.aliases.is_empty()
            {
                out.push_str(&format!("- **Aliases:** {}\n", cp.aliases.join(", ")));
            }

            // Vault folder from config.
            if let Some(folder) = cfg_project.and_then(|cp| cp.vault_folder.as_deref()) {
                out.push_str(&format!("- **Vault folder:** {folder}\n"));
            }

            // Repos from config.
            if let Some(cp) = cfg_project
                && !cp.repos.is_empty()
            {
                out.push_str(&format!("- **Repos:** {}\n", cp.repos.join(", ")));
            }

            // Component count from store.
            if let Some(p) = store_project {
                let component_count = store
                    .list_project_component_uids(&p.uid)
                    .unwrap_or_default()
                    .len();
                if component_count > 0 {
                    out.push_str(&format!("- **Components:** {component_count}\n"));
                }
            }

            // External refs from config.
            if let Some(cp) = cfg_project
                && !cp.external_refs.is_empty()
            {
                let refs_str: Vec<String> = cp
                    .external_refs
                    .iter()
                    .map(|r| {
                        if let Some(ref_type) = &r.ref_type {
                            format!("{} ({})", r.label, ref_type)
                        } else {
                            r.label.clone()
                        }
                    })
                    .collect();
                out.push_str(&format!("- **External refs:** {}\n", refs_str.join(", ")));
            }

            // Recent activity: max(note.modified_at) from project notes.
            if let Some(p) = store_project {
                let note_uids = store.list_project_note_uids(&p.uid).unwrap_or_default();
                let recent: Option<String> = note_uids
                    .iter()
                    .filter_map(|uid| store.lookup_note(uid).ok())
                    .filter_map(|n| n.modified_at)
                    .max();
                if let Some(ts) = recent {
                    out.push_str(&format!("- **Recent activity:** {ts}\n"));
                }
            }

            out.push('\n');
        }
    }

    // Section 7: Knowledge vaults
    let vaults = store.list_vaults(None).unwrap_or_default();
    if !vaults.is_empty() {
        out.push_str("## Knowledge Vaults\n\n");
        for vault in &vaults {
            let notes = store.list_notes(Some(&vault.uid)).unwrap_or_default();
            out.push_str(&format!("### {} ({} notes)\n\n", vault.name, notes.len()));
            for note in notes.iter().take(20) {
                out.push_str(&format!("- {}\n", note.title));
            }
            if notes.len() > 20 {
                out.push_str(&format!("- ... and {} more\n", notes.len() - 20));
            }
            out.push('\n');
        }
    }

    // Section 8: Available tools
    out.push_str("## NestWeaver Tools\n\n");
    out.push_str("This codebase is indexed by NestWeaver. Available MCP tools:\n\n");
    out.push_str("| Tool | Use when |\n");
    out.push_str("|------|----------|\n");
    out.push_str("| `brain_context` | Exploring unfamiliar code — seeds from symbols, files, or note titles |\n");
    out.push_str("| `brain_search` | Finding symbols or notes by keyword |\n");
    out.push_str("| `note_get` | Reading a vault note's full content |\n");
    out.push_str("| `backlinks` | Finding what links TO a note |\n");
    out.push_str("| `brain_impact` | Checking blast radius before modifying a function |\n");
    out.push_str("| `cross_repo_contracts` | Finding cross-service symbol relationships |\n");
    out.push_str("| `brain_status` | Checking what's indexed |\n");
    out.push('\n');

    // Section 9: CLI + Web
    out.push_str("## Quick Start\n\n");
    out.push_str("```bash\n");
    out.push_str("# Re-index (incremental — only changed files)\n");
    out.push_str("nestweaver index --repo .\n\n");
    out.push_str("# Search for a symbol\n");
    out.push_str("nestweaver search <name>\n\n");
    out.push_str("# Get context for a function\n");
    out.push_str("nestweaver context <name>\n\n");
    out.push_str("# Launch the web UI\n");
    out.push_str("nestweaver ui\n");
    out.push_str("```\n");

    Ok(out)
}

/// Generate a Claude Code skill file with YAML frontmatter.
///
/// Returns a skill document suitable for use as a Claude Code skill,
/// including a YAML frontmatter header and a condensed architecture section
/// derived from the indexed graph.
pub fn generate_skill(
    store: &GraphStore,
    config: Option<&InstanceConfig>,
) -> Result<String, anyhow::Error> {
    let mut out = String::new();

    out.push_str("---\n");
    out.push_str("name: nestweaver\n");
    out.push_str("description: Use when exploring code architecture, checking blast radius, understanding dependencies, or working with vault notes\n");
    out.push_str("---\n\n");

    out.push_str("## When to use NestWeaver\n\n");
    out.push_str("- **Starting a task**: Call `brain_context` with task keywords to get structural context\n");
    out.push_str(
        "- **Before modifying code**: Call `brain_impact` on the function you're changing\n",
    );
    out.push_str("- **Exploring unfamiliar code**: Call `brain_search` to find symbols or notes\n");
    out.push_str("- **Working on a project**: Call `project_context` with the project name\n");
    out.push_str(
        "- **Checking staleness**: Call `stale_check` to see if the index needs refreshing\n\n",
    );

    out.push_str("## Tools\n\n");
    out.push_str("| Tool | Use when |\n");
    out.push_str("|------|----------|\n");
    out.push_str("| brain_context | You need structural context for a task |\n");
    out.push_str("| brain_search | You need to find symbols or notes by keyword |\n");
    out.push_str("| brain_impact | You need to check blast radius before changes |\n");
    out.push_str("| brain_guide | You need an architecture overview |\n");
    out.push_str("| project_context | You're working on a named project |\n");
    out.push_str("| detect_changes | You want to assess risk of changed files |\n");
    out.push_str("| brain_status | You need to check what's indexed |\n");
    out.push_str("| brain_diff | You want to see what changed since last index |\n");
    out.push_str("| flow_trace | You need to trace execution flow from a symbol |\n");
    out.push_str("| note_get | You need the full body of a specific note |\n\n");

    out.push_str("## Codebase\n\n");

    // Repos list
    let repos = store.list_repos(None).unwrap_or_default();
    if repos.is_empty() {
        out.push_str("No repositories indexed yet.\n\n");
    } else {
        for repo in &repos {
            let sha_short = if repo.indexed_sha.len() >= 8 {
                &repo.indexed_sha[..8]
            } else {
                &repo.indexed_sha
            };
            out.push_str(&format!("- `{}` (sha: {})\n", repo.url, sha_short));
        }
        out.push('\n');
    }

    // Condensed repo map
    match crate::query::generate_repo_map(store, 1000) {
        Ok(map) => {
            out.push_str("```\n");
            out.push_str(&map);
            out.push_str("\n```\n");
        }
        Err(_) => {
            out.push_str("No symbols indexed yet.\n");
        }
    }

    let _ = config; // reserved for future use

    Ok(out)
}

/// Generate a Cursor rule file with MDC frontmatter.
///
/// Returns content suitable for writing to `.cursor/rules/nestweaver.mdc`.
pub fn generate_cursor_rule(
    store: &GraphStore,
    config: Option<&InstanceConfig>,
) -> Result<String, anyhow::Error> {
    let _ = (store, config); // no dynamic content needed for the base rule

    let mut out = String::new();

    out.push_str("---\n");
    out.push_str("description: Use NestWeaver for structural codebase understanding and blast radius analysis\n");
    out.push_str("globs:\n");
    out.push_str("alwaysApply: true\n");
    out.push_str("---\n\n");

    out.push_str("When exploring unfamiliar code, use the `brain_context` MCP tool with relevant symbol names as seeds to get PPR-ranked structural context.\n\n");
    out.push_str("Before modifying functions with many callers, use `brain_impact` to check blast radius.\n\n");
    out.push_str("For architecture questions, use `brain_guide` to get the auto-generated codebase intelligence guide.\n\n");
    out.push_str("When working on a named project, use `project_context` to get project-scoped notes and symbols.\n\n");
    out.push_str("After making changes, use `detect_changes` to assess risk.\n");

    Ok(out)
}

/// Generate an AGENTS.md file for Codex with a Codex-specific header.
///
/// Returns the same content as `generate_guide` but prefixed with a
/// Codex-oriented header explaining the file's purpose.
pub fn generate_agents_md(
    store: &GraphStore,
    config: Option<&InstanceConfig>,
) -> Result<String, anyhow::Error> {
    let mut out = String::new();

    out.push_str("# AGENTS.md — Codebase Intelligence Guide\n\n");
    out.push_str("> Auto-generated by NestWeaver. This file helps AI agents understand the codebase structure.\n");
    out.push_str("> NestWeaver provides 17 MCP tools for code intelligence. Run `nestweaver mcp` to start the server.\n\n");

    let guide = generate_guide(store, config)?;
    out.push_str(&guide);

    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generate_guide_produces_valid_markdown() {
        let store = nestweaver_store::GraphStore::in_memory().unwrap();
        let guide = generate_guide(&store, None).unwrap();
        assert!(guide.contains("# Codebase Intelligence Guide"));
        assert!(guide.contains("## NestWeaver Tools"));
        assert!(guide.contains("brain_context"));
    }

    #[test]
    fn generate_skill_produces_yaml_frontmatter() {
        let store = nestweaver_store::GraphStore::in_memory().unwrap();
        let skill = generate_skill(&store, None).unwrap();
        assert!(skill.starts_with("---\n"));
        assert!(skill.contains("name: nestweaver"));
        assert!(skill.contains("brain_context"));
    }

    #[test]
    fn generate_cursor_rule_produces_mdc_frontmatter() {
        let store = nestweaver_store::GraphStore::in_memory().unwrap();
        let rule = generate_cursor_rule(&store, None).unwrap();
        assert!(rule.starts_with("---\n"));
        assert!(rule.contains("alwaysApply: true"));
        assert!(rule.contains("brain_context"));
    }

    #[test]
    fn generate_agents_md_produces_codex_header() {
        let store = nestweaver_store::GraphStore::in_memory().unwrap();
        let agents_md = generate_agents_md(&store, None).unwrap();
        assert!(agents_md.starts_with("# AGENTS.md"));
        assert!(agents_md.contains("17 MCP tools"));
        assert!(agents_md.contains("# Codebase Intelligence Guide"));
    }
}
